"""5 qubit 的 1023 個實參數是怎麼來的，以及為什麼它「不是」可訓練參數量。

這是一個很容易被誤用的數字，本腳本把它拆開講清楚。
"""

from __future__ import annotations

import numpy as np

N = 5
D = 2 ** N
print("=" * 78)
print(f"{N} qubit：希爾伯特空間維度 d = 2^{N} = {D}")
print("=" * 78)

# ---------------------------------------------------------------------------
# 1. 密度矩陣的自由度
# ---------------------------------------------------------------------------
print("\n[1] 密度矩陣 ρ 的自由度推導")
print(f"    ρ 是 d×d 的矩陣，d = {D}")
print(f"    若是一般複數矩陣：{D}×{D}×2 = {D*D*2} 個實數")
print()
print("    但 ρ 必須滿足兩個條件：")
print(f"      (a) Hermitian：ρ = ρ†")
print(f"          對角線 {D} 個必須是實數 → 省下 {D} 個")
print(f"          非對角線有 {D*(D-1)//2} 對，每對共軛 → 省下 {D*(D-1)//2}×2 = {D*(D-1)} 個")
print(f"      (b) 跡為 1：Tr[ρ] = 1 → 再省下 1 個")
print()
free = D * D - 1
print(f"    自由度 = d² − 1 = {D}² − 1 = {D*D} − 1 = {free}")
print(f"    → 這就是 1023 的來源，與 qubit 數的關係是 4^n − 1")

for n in range(1, 8):
    dn = 2 ** n
    print(f"      n={n}: d={dn:>3}, ρ 自由度 = {dn*dn-1:>6}")

# ---------------------------------------------------------------------------
# 2. 但這不是「可訓練參數量」
# ---------------------------------------------------------------------------
print("\n" + "=" * 78)
print("[2] 關鍵區別：狀態空間的維度 ≠ 電路的可訓練參數量")
print("=" * 78)
print("""
    1023 是「所有可能的 5 qubit 量子態」這個集合的維度。
    我們的電路只能碰到其中極小的一塊——因為電路只有少數幾個可調旋鈕。

    打個比方：
      · 所有 32 維機率分布是一個 31 維的單純形（連續統，不可數）
      · 但 softmax 只有 31 個參數，只能碰到其中一個 31 維的子流形
      · 「31」不是單純形的維度，而是模型的參數量

    同理，1023 是 ρ 空間的維度，不是我們電路的參數量。
""")

# --- 實際計算本專案各層的參數量 ---
print("-" * 78)
print("本專案各層的實際可訓練參數量")
print("-" * 78)

rows = []

# 編碼層：5 個 RY，角度由前端特徵決定 → 不是可訓練參數
enc_params = 0
rows.append(("角度編碼層（5 個 RY，角度來自前端）", enc_params, "不可訓練：由輸入決定"))

# 可訓練旋轉層：5 個 RY + 5 個 RZ
train_per_layer = N + N
for layers in (1, 2, 3):
    rows.append((f"可訓練旋轉層 × {layers}（每層 {N} 個 RY 加 {N} 個 RZ）",
                 train_per_layer * layers, "可訓練"))

# 糾纏層：CX 沒有參數
rows.append(("環形 CX 糾纏層（5 個 CX）", 0, "無參數（閘是固定的）"))

# 讀出層
for K in (2, 3, 10, 32):
    rows.append((f"POVM 讀出 W（32→{K}）", 32 * K, "可訓練"))

# 古典對照
rows.append(("softmax 頭（5→K，K=10）", 5 * 10 + 10, "可訓練：權重 + 偏置"))
rows.append(("古典全連接（256→10）", 256 * 10 + 10, "可訓練"))
rows.append(("古典全連接（32→10）", 32 * 10 + 10, "可訓練"))
rows.append(("一般 32×32 複數線性映射", 32 * 32 * 2, "⚠️ 這才是使用者直覺的那個"))

print(f"\n    {'項目':<44} {'參數量':>8}  備註")
print("    " + "-" * 78)
for name, cnt, note in rows:
    print(f"    {name:<44} {cnt:>8}  {note}")

# ---------------------------------------------------------------------------
# 3. 使用者直覺的檢驗：它像 32×32 的單層過濾器嗎？
# ---------------------------------------------------------------------------
print("\n" + "=" * 78)
print("[3] 「像 32×32 的單層過濾器」這個直覺對不對？")
print("=" * 78)
print(f"""
    一半對，一半是關鍵誤解。

    ✅ 對的部分：
       32×32 是一個線性映射，要 {32*32*2} 個實數；ρ 要 {D*D} 個實數（其中 {free} 個自由）。
       兩者的「容器大小」同量級，都是 O(d²)。所以「容量相當於一個 32×32 的東西」是合理的。

    ❌ 關鍵誤解：
       ρ 是**狀態（state）**，不是**映射（map）**。
         · 狀態 = 「系統現在長什麼樣」→ 是一個點
         · 映射 = 「把輸入變成輸出」→ 是一個函數
       ρ 不會把任何東西變成別的東西；它是被製備出來的結果。

       在 QBN 的語言裡：
         · 節點的通道 E_i（CPTP 映射）才是「過濾器」，它的維度是 d_out² × d_in² 級
         · ρ 是通道作用之後的產物

       所以正確的說法是：
         「5 qubit 的**狀態空間**有 1023 個自由度」
         不是
         「5 qubit 輸出層有 1023 個可訓練參數」
""")

# ---------------------------------------------------------------------------
# 4. 那我們真正的容量瓶頸在哪？
# ---------------------------------------------------------------------------
print("=" * 78)
print("[4] 真正的容量比較（1 層電路）")
print("=" * 78)

enc = 0                      # 編碼層角度由輸入決定，不可訓練
n_train = N + N              # 1 層可訓練旋轉：5 個 RY 加 5 個 RZ
readout_K10 = 32 * 10
softmax_head = 5 * 10 + 10   # 5→10 的權重加偏置
total_1layer = n_train + readout_K10
print(f"""
    我們的 1 層電路（K=10）：
      編碼層            {enc:>4} 個可訓練參數（由輸入決定）
      可訓練旋轉層      {n_train:>4} 個（5 個 RY 加 5 個 RZ）
      讀出層 W          {readout_K10:>4} 個（32×10 矩陣）
      ────────────────────────────
      合計              {total_1layer:>4} 個可訓練參數

    古典 softmax 頭（接在同樣的 5 維特徵上，K=10）：
      權重加偏置        {softmax_head:>4} 個可訓練參數

    ★ 所以「1023 對比 31」是**不公平的**：
      1023 是狀態空間維度；古典模型在 5 維輸入、K 類時是 31 個參數，
      但我們的電路輸出 32 維，對應的古典類比是 32 維輸入的 softmax（1023 個參數）。
      在任何情況下，「狀態空間維度」都不該直接和「模型參數量」相比。

    ★ 我們真正該比的是 {total_1layer} 對 {softmax_head}。

    ★ 更誠實的說法：
      問題不是「誰的參數多」，而是
      「{n_train} 個可訓練角度所張開的狀態流形，能不能參數化出 softmax 造不出的分布？」
      這是一個**沒有先驗答案**的實證問題，也是本專案該做的實驗。
""")

print("=" * 78)
